// Writes docs/tools.md from what the server advertises over tools/list, so the reference
// cannot drift from the schemas agents actually receive. CI fails when the file is stale.
import { writeFileSync } from "node:fs";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { createGitHub } from "../src/github.ts";
import { createServer } from "../src/server.ts";

const client = new Client({ name: "gen-docs", version: "0" });
const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
await createServer(createGitHub()).connect(serverSide);
await client.connect(clientSide);
const { tools } = await client.listTools();
await client.close();

const json = (v: unknown) => `\`\`\`json\n${JSON.stringify(v, null, 2)}\n\`\`\``;
const md = [
  "# Tool reference",
  "",
  "Generated by `npm run docs` from the server's `tools/list` response. Do not edit by hand.",
  ...tools.flatMap((t) => [
    "",
    `## \`${t.name}\``,
    "",
    t.description ?? "",
    "",
    `Annotations: ${Object.entries(t.annotations ?? {})
      .map(([k, v]) => `\`${k}: ${v}\``)
      .join(", ")}`,
    "",
    "### Input schema",
    "",
    json(t.inputSchema),
    "",
    "### Output schema",
    "",
    json(t.outputSchema),
  ]),
  "",
].join("\n");
writeFileSync(new URL("../docs/tools.md", import.meta.url), md);
